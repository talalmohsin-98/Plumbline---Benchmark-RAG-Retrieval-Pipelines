"""Rebuild the demo corpus from pinned upstream documentation.

The published numbers are measured on a specific snapshot of three MIT-licensed
documentation sets. This script is how a stranger reproduces that snapshot:

    python scripts/fetch_corpus.py              # rebuild the pinned corpus
    python scripts/fetch_corpus.py --latest     # re-pin to current upstream HEAD

`data/demo_corpus/MANIFEST.json` is the pin. It is committed; the corpus
content is not. Running with no flags fetches the exact commits the manifest
names, so the corpus is byte-reproducible rather than merely "the same repos,
some time later". `--latest` is the only way to move the pin, and it rewrites
the manifest, which shows up as a reviewable diff.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import stat
import subprocess
import sys
import tempfile
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path, PurePosixPath

REPO_ROOT = Path(__file__).resolve().parent.parent
CORPUS_DIR = REPO_ROOT / "data" / "demo_corpus"
MANIFEST_PATH = CORPUS_DIR / "MANIFEST.json"
MANIFEST_VERSION = 1

# Stubs, redirect pages, and bare index pages carry no retrievable content but
# would inflate the chunk count and dilute every metric.
MIN_FILE_BYTES = 500

# Autogenerated API dumps are near-duplicate boilerplate: hundreds of pages of
# signatures that differ by a few tokens. They would pad the corpus, and a gold
# question drawn from one is answerable equally well by fifty others.
EXCLUDED_PATH_FRAGMENTS = ("/api_reference/", "/reference/")

# Changelogs are the same problem in a single file. fastapi/release-notes.md
# alone produced 644 chunks — 23% of the unfiltered corpus — of "* Fix X. PR
# #1234 by @user". It fails the evaluation spec's own first drop-rule: any
# question drawn from it is answered equally well by fifty other chunks.
EXCLUDED_FILENAME_FRAGMENTS = ("release-notes", "changelog")

# Documentation sites conventionally prefix partials, fixtures, and snippets
# with an underscore. FastAPI's `_llm-test.md` is one: a test fixture, not
# documentation. It contributed 7 chunks, one of which produced a passage so
# incoherent the drafting model replied "Could you provide the passage you'd
# like the question to be based on?".
EXCLUDED_STEM_PREFIX = "_"

DOC_SUFFIXES = (".md", ".mdx")

# Selection profile "G". The unfiltered corpus is 2854 chunks against a budget
# of 1000-1500 (docs/03_BUILD_PLAN.md, Day 1). Two thirds of it sits in
# top-level concept pages, so trimming subdirectories alone cannot reach the
# budget; this profile keeps every source's top-level pages and only those
# subdirectories named in `Source.keep_subdirs`. Measured result: 1487 chunks
# across 128 files, balanced across all three sources.
SELECTION_PROFILE = "G"


@dataclass(frozen=True)
class Source:
    """One documentation tree to extract from one upstream repository."""

    name: str
    repo: str
    docs_path: str
    license: str
    # Subdirectories kept despite the top-level-only rule. Everything else
    # below the docs root is dropped.
    keep_subdirs: tuple[str, ...] = ()


# Upstream moved since these were first written, and both LangChain paths in the
# original brief now 404. Verified 2026-08-12:
#   - langgraph-ai/langgraph          does not exist; the repo is langchain-ai/langgraph
#   - langchain-ai/langchain          no longer has a docs/ tree at all
#   - langchain-ai/langgraph docs/    holds only redirects and llms.txt
# LangChain and LangGraph prose now lives in the consolidated langchain-ai/docs
# repository (MIT) under src/oss/, as .mdx. Both entries below therefore point
# at one repo and two subtrees; the clone is shared.
SOURCES: tuple[Source, ...] = (
    Source(
        name="fastapi",
        repo="https://github.com/fastapi/fastapi.git",
        docs_path="docs/en/docs",
        license="MIT",
        # 51 short, task-specific pages ("how do I declare a query parameter").
        # That shape is what makes recall@k discriminate between lanes, so it
        # is worth the ~233 chunks it costs.
        keep_subdirs=("tutorial",),
    ),
    Source(
        name="langchain",
        repo="https://github.com/langchain-ai/docs.git",
        docs_path="src/oss/langchain",
        license="MIT",
    ),
    Source(
        name="langgraph",
        repo="https://github.com/langchain-ai/docs.git",
        docs_path="src/oss/langgraph",
        license="MIT",
    ),
)


class CorpusError(RuntimeError):
    """A fetch failed. The corpus is never left half-built."""


# --------------------------------------------------------------------------
# git plumbing
# --------------------------------------------------------------------------


def git(args: list[str], cwd: Path | None = None) -> str:
    """Run a git command, raising CorpusError with stderr on any failure."""
    result = subprocess.run(
        ["git", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode != 0:
        raise CorpusError(
            f"git {' '.join(args)} failed with exit code {result.returncode}\n"
            f"{result.stderr.strip()}"
        )
    return result.stdout.strip()


def _force_remove(func, path, _exc_info) -> None:  # noqa: ANN001
    """Clear the read-only bit git sets on pack files, then retry.

    Without this, cleaning up a clone raises PermissionError on Windows and
    leaves the temp directory behind.
    """
    Path(path).chmod(stat.S_IWRITE)
    func(path)


def remove_tree(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path, onerror=_force_remove)


def sparse_fetch(repo: str, ref: str, docs_paths: list[str], dest: Path) -> str:
    """Fetch just `docs_paths` of `repo` at `ref` into `dest`; return the commit.

    Blobless and sparse: these repositories are hundreds of megabytes and we
    want a few subtrees. `git init` + `fetch <sha>` rather than
    `clone --revision` because fetching an explicit commit works on older git,
    and pinning to a commit is the entire point of the manifest.

    All of a repository's paths are set in one `sparse-checkout set` call.
    LangChain and LangGraph share a clone, and adding their subtrees one at a
    time would leave whichever came second missing from the working tree.
    """
    dest.mkdir(parents=True, exist_ok=True)
    git(["init", "--quiet"], cwd=dest)
    git(["remote", "add", "origin", repo], cwd=dest)
    git(["fetch", "--depth", "1", "--filter=blob:none", "origin", ref], cwd=dest)
    git(["sparse-checkout", "init", "--cone"], cwd=dest)
    git(["sparse-checkout", "set", *docs_paths], cwd=dest)
    git(["checkout", "--quiet", "FETCH_HEAD"], cwd=dest)

    commit = git(["rev-parse", "HEAD"], cwd=dest)
    missing = [p for p in docs_paths if not (dest / p).is_dir()]
    if missing:
        raise CorpusError(
            f"{repo} at {commit[:12]} has no directory {missing!r}. "
            "Upstream has moved it; fix the SOURCES table rather than "
            "silently shipping a smaller corpus."
        )
    return commit


# --------------------------------------------------------------------------
# selection
# --------------------------------------------------------------------------


SKIP_REASONS = ("reference", "boilerplate", "fixture", "subdirectory", "too_small")


def skip_reason(relative_posix: str, size_bytes: int, keep_subdirs: tuple[str, ...]) -> str | None:
    """Why this file is excluded, or None to keep it.

    `relative_posix` is relative to the source's docs root, so a top-level page
    has no slash in it.
    """
    probe = "/" + relative_posix.lstrip("/")
    if any(fragment in probe for fragment in EXCLUDED_PATH_FRAGMENTS):
        return "reference"

    stem = PurePosixPath(relative_posix).stem.lower()
    if any(fragment in stem for fragment in EXCLUDED_FILENAME_FRAGMENTS):
        return "boilerplate"
    if stem.startswith(EXCLUDED_STEM_PREFIX):
        return "fixture"

    if "/" in relative_posix:
        top = relative_posix.split("/", 1)[0]
        if top not in keep_subdirs:
            return "subdirectory"

    # Size last, so the tally attributes a file to the rule that describes it
    # rather than to whichever check happened to run first.
    if size_bytes < MIN_FILE_BYTES:
        return "too_small"
    return None


def select_files(source: Source, docs_root: Path) -> tuple[list[Path], dict[str, int]]:
    """Return the doc files to keep, plus a tally of why others were dropped."""
    kept: list[Path] = []
    skipped = dict.fromkeys(SKIP_REASONS, 0)

    for path in sorted(docs_root.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in DOC_SUFFIXES:
            continue
        relative = path.relative_to(docs_root).as_posix()
        reason = skip_reason(relative, path.stat().st_size, source.keep_subdirs)
        if reason is None:
            kept.append(path)
        else:
            skipped[reason] += 1

    return kept, skipped


def stage_source(source: Source, docs_root: Path, staging: Path) -> dict[str, object]:
    """Copy one source's selected files into the staging tree."""
    kept, skipped = select_files(source, docs_root)
    if not kept:
        raise CorpusError(
            f"{source.name}: no documents survived filtering under {source.docs_path!r}. "
            "That is a broken source path, not an empty corpus."
        )

    target_root = staging / source.name
    total_bytes = 0
    for path in kept:
        relative = path.relative_to(docs_root)
        destination = target_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
        total_bytes += destination.stat().st_size

    return {
        "file_count": len(kept),
        "byte_count": total_bytes,
        "skipped": skipped,
    }


# --------------------------------------------------------------------------
# manifest
# --------------------------------------------------------------------------


def iter_corpus_files(root: Path) -> Iterator[Path]:
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.name != MANIFEST_PATH.name:
            yield path


def content_digest(root: Path) -> str:
    """A single hash over every corpus file's path and bytes.

    Lets a stranger prove their rebuild matches the one the numbers came from,
    without diffing thousands of files.
    """
    digest = hashlib.sha256()
    for path in iter_corpus_files(root):
        digest.update(path.relative_to(root).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def load_pins() -> dict[str, str]:
    """Read source-name -> commit from an existing manifest, if there is one."""
    if not MANIFEST_PATH.exists():
        return {}
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    return {entry["name"]: entry["commit"] for entry in manifest.get("sources", [])}


def build_manifest(entries: list[dict[str, object]], digest: str) -> dict[str, object]:
    return {
        "manifest_version": MANIFEST_VERSION,
        "fetched_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "selection_profile": SELECTION_PROFILE,
        "filters": {
            "min_file_bytes": MIN_FILE_BYTES,
            "excluded_path_fragments": list(EXCLUDED_PATH_FRAGMENTS),
            "excluded_filename_fragments": list(EXCLUDED_FILENAME_FRAGMENTS),
            "excluded_stem_prefix": EXCLUDED_STEM_PREFIX,
            "suffixes": list(DOC_SUFFIXES),
            "subdirectories": (
                "top-level pages only, except each source's keep_subdirs"
            ),
        },
        "totals": {
            "files": sum(int(e["file_count"]) for e in entries),
            "bytes": sum(int(e["byte_count"]) for e in entries),
        },
        "content_sha256": digest,
        "sources": entries,
    }


# --------------------------------------------------------------------------
# pipeline
# --------------------------------------------------------------------------


def existing_source_dirs() -> list[Path]:
    if not CORPUS_DIR.is_dir():
        return []
    return [p for p in sorted(CORPUS_DIR.iterdir()) if p.is_dir()]


def fetch(
    sources: Iterable[Source],
    pins: dict[str, str],
    staging: Path,
) -> list[dict[str, object]]:
    """Fetch and stage every source. Any failure aborts before anything moves."""
    entries: list[dict[str, object]] = []
    sources = list(sources)
    work = Path(tempfile.mkdtemp(prefix="plumbline-corpus-"))

    # Group by (repo, ref) so a shared repository is fetched exactly once with
    # every subtree it has to supply.
    groups: dict[tuple[str, str], list[str]] = {}
    for source in sources:
        key = (source.repo, pins.get(source.name, "HEAD"))
        groups.setdefault(key, [])
        if source.docs_path not in groups[key]:
            groups[key].append(source.docs_path)

    try:
        clones: dict[tuple[str, str], tuple[Path, str]] = {}
        for index, ((repo, ref), docs_paths) in enumerate(groups.items()):
            slug = repo.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")
            dest = work / f"{slug}-{index}"
            shown = ref if ref == "HEAD" else ref[:12]
            print(f"  fetching {repo} @ {shown} -> {', '.join(docs_paths)}")
            clones[(repo, ref)] = (dest, sparse_fetch(repo, ref, docs_paths, dest))

        for source in sources:
            clone_dir, commit = clones[(source.repo, pins.get(source.name, "HEAD"))]

            license_file = clone_dir / "LICENSE"
            if not license_file.is_file():
                print(f"  WARNING: no LICENSE file at the root of {source.repo}")

            stats = stage_source(source, clone_dir / source.docs_path, staging)
            entries.append(
                {
                    "name": source.name,
                    "url": source.repo,
                    "docs_path": source.docs_path,
                    "commit": commit,
                    "license": source.license,
                    "license_file_present": license_file.is_file(),
                    "keep_subdirs": list(source.keep_subdirs),
                    **stats,
                }
            )
    finally:
        remove_tree(work)

    return entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python scripts/fetch_corpus.py",
        description="Rebuild the pinned demo corpus from upstream documentation.",
    )
    parser.add_argument(
        "--latest",
        action="store_true",
        help="ignore the pinned commits and re-pin to upstream HEAD",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing corpus",
    )
    args = parser.parse_args(argv)

    present = existing_source_dirs()
    if present and not args.force:
        names = ", ".join(p.name for p in present)
        print(
            f"Refusing to overwrite an existing corpus in {CORPUS_DIR} (found: {names}).\n"
            "The corpus the published numbers were measured on may already be here.\n"
            "Re-run with --force to replace it.",
            file=sys.stderr,
        )
        return 1

    pins = {} if args.latest else load_pins()
    if pins:
        print(f"Rebuilding from the pinned commits in {MANIFEST_PATH.name}.")
    elif args.latest:
        print("Re-pinning to upstream HEAD.")
    else:
        print("No manifest found; fetching upstream HEAD and writing a new pin.")

    staging = CORPUS_DIR.parent / ".demo_corpus.staging"
    remove_tree(staging)
    staging.mkdir(parents=True)

    try:
        entries = fetch(SOURCES, pins, staging)
        digest = content_digest(staging)
        manifest = build_manifest(entries, digest)
        (staging / MANIFEST_PATH.name).write_text(
            json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
        )
        (staging / ".gitkeep").touch()

        # Swap in only once every source has succeeded.
        remove_tree(CORPUS_DIR)
        staging.replace(CORPUS_DIR)
    except BaseException:
        remove_tree(staging)
        raise

    print(f"\nselection profile {SELECTION_PROFILE}\n")
    for entry in entries:
        skipped: dict[str, int] = entry["skipped"]  # type: ignore[assignment]
        detail = ", ".join(f"{skipped[reason]} {reason}" for reason in SKIP_REASONS)
        print(
            f"  {entry['name']:<12} {entry['file_count']:>5} files  "
            f"{int(entry['byte_count']) / 1_000_000:>6.2f} MB  "
            f"@ {str(entry['commit'])[:12]}"
        )
        print(f"  {'':<12} skipped: {detail}")
    totals: dict[str, int] = manifest["totals"]  # type: ignore[assignment]
    print(f"  {'TOTAL':<12} {totals['files']:>5} files")
    print(f"\n  content_sha256 {digest}")
    print(f"  manifest       {MANIFEST_PATH}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except CorpusError as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        sys.exit(1)
